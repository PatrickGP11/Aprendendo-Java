package flamingo.aprendendo.basico.ExerciciosEstruturaDeRepeticao;

public class Ex04 {
    static void main(String[] args) {
        int soma = 0;
        for (int i = 1; i <= 100; i++) {
            soma += i;
        }
        System.out.println("A soma de 1 até 100 é: " + soma);
    }
}
